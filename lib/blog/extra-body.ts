export function mergeBlogExtra(a: BlogArticle): BlogArticle {
  const extra = BLOG_EXTRA_SECTIONS[a.slug];
  const withExtra = extra?.length
    ? { ...a, sections: [...a.sections, ...extra] }
    : a;
  return withExtra;
}
